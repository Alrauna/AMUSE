        /// <summary>
        /// The off test of a uniform switch. The source compares with
        /// not equal to zero, so a NaN keeps the family live.
        /// </summary>
        private static Func<Material, string, bool> SwitchIsOff(
            string switchProperty)
        {
            return (material, rowName) =>
                material.GetFloat(switchProperty) == 0f;
        }

        /// <summary>
        /// The off test of the dissolve mode. The function rounds the
        /// mode before it reads it, so a mode between minus one half
        /// and one half rounds to zero. A NaN mode keeps the family
        /// live.
        /// </summary>
        private static bool DissolveModeIsOff(
            Material material, string rowName)
        {
            var mode = material.GetVector("_DissolveParams").x;
            return mode > -0.5f && mode < 0.5f;
        }

        private static bool RowIsOpaque(string rowName)
        {
            return rowName.IndexOf("Transparent", StringComparison.Ordinal) < 0 &&
                   rowName.IndexOf("Cutout", StringComparison.Ordinal) < 0;
        }

        private static bool RowHasNoOutlinePass(string rowName)
        {
            return rowName.IndexOf("Outline", StringComparison.Ordinal) < 0;
        }

