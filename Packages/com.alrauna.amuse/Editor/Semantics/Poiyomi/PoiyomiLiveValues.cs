        /// <summary>
        /// One dead value family per refused keyword. The only
        /// switch is the keyword. The family is dead when the
        /// material does not enable the keyword, so an old texture
        /// of a refused feature whose keyword is off leaves the
        /// material key.
        /// </summary>
        private static AtlasDeadValueFamily KeywordFamily(
            string keyword,
            string[] members)
        {
            return new AtlasDeadValueFamily(
                keyword,
                new[] { keyword },
                (material, rowName) => !material.IsKeywordEnabled(keyword),
                members);
        }

